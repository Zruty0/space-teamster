// Publish a reviewed offline fit, never refit against a live board. Overwrite requires --replace.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const [input, output] = process.argv.slice(2);
const replace = process.argv.includes('--replace');
if (!input || !output) throw Error('Usage: node tests/write-origin-income-data.mjs FIT.json NEW_OUTPUT.ts');
const raw = await readFile(input, 'utf8'), fit = JSON.parse(raw);
for (const [key, curve] of Object.entries(fit.curves)) {
  if (!key.includes('|') || ![1, 8].includes(curve.length) || curve.some((n,i) => !Number.isFinite(n) || n <= 0 || (i && n < curve[i-1]))) throw Error('Invalid origin curve: '+key);
}
for (const [key, value] of Object.entries(fit.routeWorkloads)) if (!key.includes('|') || !Number.isFinite(value) || value <= 0) throw Error('Invalid route workload: '+key);
for (const [key, values] of Object.entries(fit.fees)) if (values.length !== 6 || values.some((n,i) => !Number.isFinite(n) || n <= 0 || (i % 2 === 1 && n < values[i-1]))) throw Error('Invalid employer fee anchors: '+key);
const entries = object => Object.entries(object).sort(([a],[b])=>a.localeCompare(b)).map(([k,v])=>'  '+JSON.stringify(k)+': '+JSON.stringify(v)+',').join('\n');
const content = `// Generated by tests/write-origin-income-data.mjs; no runtime fitting or board quotas.
// Reference: ${fit.reference ? fit.reference.appearances+' appearances over '+fit.reference.days.length+' sampled days' : 'see originating fit report'}.
// Fit SHA-256: ${createHash('sha256').update(raw).digest('hex')}
import type { OriginIncomeCurve, OriginFeeCurve } from './origin-income-math';
export const ORIGIN_INCOME_REFERENCE = ${JSON.stringify(fit.reference ?? { appearances: 0, days: [] })} as const;
/** Physical departure terminal | freight/passenger. Single knots are sparse entry markets. */
export const ORIGIN_INCOME_CURVES: Readonly<Record<string, OriginIncomeCurve>> = {
${entries(fit.curves)}
};
/** Fixed reference fuel workload per loaded tonne, source → destination. Not an actual fuel quote. */
export const ORIGIN_ROUTE_WORKLOADS: Readonly<Record<string, number>> = {
${entries(fit.routeWorkloads)}
};
/** Employer fee medians after local band selection: low/high pairs for bands 0, 1 and 2. */
export const ORIGIN_EMPLOYER_FEES: Readonly<Record<string, OriginFeeCurve>> = {
${entries(fit.fees)}
};
`;
await writeFile(output, content, { flag: replace ? 'w' : 'wx' });
console.log(`Wrote ${Object.keys(fit.curves).length} origin markets / ${Object.keys(fit.routeWorkloads).length} route references to ${output}`);
